#!/usr/bin/env node
// Bundles the library's skills into connector/src/skills.generated.js for the
// Worker to serve. Reads from the committed HEAD (git ls-files and git show),
// never the working tree, so gitignored vendor packs and uncommitted edits
// cannot reach the public connector.
//
// usage: node connector/scripts/build.mjs [--repo <path>]

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const argRepo = process.argv.indexOf('--repo');
const repo = resolve(argRepo > -1 ? process.argv[argRepo + 1] : join(here, '..', '..'));
const out = join(here, '..', 'src', 'skills.generated.js');

const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const show = (path) => git('show', `HEAD:${path}`);

// Top-level skills only: <dir>/SKILL.md. Nested ones (org-skills/...) are not
// part of the indexed library.
const skillFiles = git('ls-files', '*/SKILL.md')
  .split('\n')
  .filter((p) => /^[^/]+\/SKILL\.md$/.test(p));

function frontmatter(text, path) {
  const lines = text.split(/\r?\n/);
  if (lines[0] !== '---') throw new Error(`${path}: no frontmatter`);
  const end = lines.indexOf('---', 1);
  if (end < 0) throw new Error(`${path}: unterminated frontmatter`);
  const fm = {};
  for (let i = 1; i < end; i++) {
    const m = /^([a-zA-Z_-]+):\s*(.*)$/.exec(lines[i]);
    if (!m) continue;
    let value = m[2];
    if (/^[>|]-?$/.test(value)) {
      const parts = [];
      while (i + 1 < end && /^\s+\S/.test(lines[i + 1])) parts.push(lines[++i].trim());
      value = parts.join(' ');
    }
    value = value.replace(/^(['"])(.*)\1$/, '$2');
    fm[m[1]] = value;
  }
  return { fm, body: lines.slice(end + 1).join('\n') };
}

const allTracked = git('ls-files').split('\n').filter(Boolean);
const skills = [];
for (const path of skillFiles) {
  const dir = path.split('/')[0];
  const text = show(path);
  const { fm, body } = frontmatter(text, path);
  if (fm.name !== dir) throw new Error(`${path}: name "${fm.name}" does not match its folder`);
  if (!fm.description) throw new Error(`${path}: empty description`);
  const headings = body
    .split('\n')
    .filter((l) => /^#{1,3} /.test(l))
    .map((l) => l.replace(/^#+ /, '').trim());
  const files = {};
  for (const f of allTracked) {
    if (!f.startsWith(`${dir}/`) || f === path || !f.endsWith('.md')) continue;
    files[f.slice(dir.length + 1)] = show(f);
  }
  skills.push({ name: fm.name, description: fm.description, headings, text, files });
}
skills.sort((a, b) => a.name.localeCompare(b.name));

const commit = git('rev-parse', '--short', 'HEAD').trim();
const builtFrom = { commit, count: skills.length };
writeFileSync(
  out,
  `// Generated by connector/scripts/build.mjs from commit ${commit}. Do not edit.\n` +
    `export const BUILT_FROM = ${JSON.stringify(builtFrom)};\n` +
    `export const SKILLS = ${JSON.stringify(skills)};\n`,
);
const bytes = skills.reduce((n, s) => n + s.text.length + Object.values(s.files).join('').length, 0);
console.log(`ok: ${skills.length} skills from ${commit}, ${Math.round(bytes / 1024)} KB of text -> ${out}`);
